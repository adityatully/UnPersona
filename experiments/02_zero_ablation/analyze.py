"""Experiment 02 tables from the judged files.  Env: interp (pandas only).
python experiments/02_zero_ablation/analyze.py

Reads <cond>_codex.csv (columns: sys_idx, q_idx, question, answer, evil, coherence; evil NaN = judge said REFUSAL)
written by `python -m unpersona.codex_judge collect`. Writes results.md next to this script.
"""
import json
import os

import pandas as pd

OUT = "/data/coe9/artifacts/unpersona/exp02_zero_ablation"
HERE = os.path.dirname(os.path.abspath(__file__))
CONDS = ["evil_base", "evil_ablate", "evil_ortho", "evil_mean", "noprompt_base", "noprompt_ablate", "noprompt_mean"]

d = {c: pd.read_csv(f"{OUT}/{c}_codex.csv") for c in CONDS}
lines = ["# Experiment 02 results (generated by analyze.py)\n"]

# 1. one row per condition
rows = []
for c, df in d.items():
    rows.append(dict(condition=c, n=len(df), evil_mean=df.evil.mean(), evil_std=df.evil.std(),
                     frac_evil_ge50=(df.evil >= 50).mean(), coherence_mean=df.coherence.mean(),
                     coherence_std=df.coherence.std(), refusals=int(df.evil.isna().sum()),
                     finished=df.finished.mean(), answer_tokens=df.n_answer_tokens.mean()))
lines += ["## Per condition\n", "```\n" + pd.DataFrame(rows).round(2).to_string(index=False) + "\n```", ""]

# 2. system prompt x condition (evil conditions), mean evil / coherence
t = pd.concat({c: d[c].groupby("sys_idx")[["evil", "coherence"]].mean() for c in CONDS[:4]}, axis=1)
lines += ["## Evil system prompt (0-4) x condition: mean evil, coherence over 20 questions\n", "```\n" + t.round(1).to_string() + "\n```", ""]

# 3. question x condition
q = pd.concat({c: d[c].groupby("q_idx").evil.mean() for c in CONDS}, axis=1)
lines += ["## Question (0-19) x condition: mean evil (evil conditions: over 5 system prompts; noprompt: 1 answer)\n",
          "```\n" + q.round(1).to_string() + "\n```", ""]

# 4. ortho check
chk = f"{OUT}/ortho_check.json"
if os.path.exists(chk):
    lines += ["## Hooks vs weight orthogonalization\n", "```", json.dumps(json.load(open(chk)), indent=1), "```", ""]

open(f"{HERE}/results.md", "w").write("\n".join(lines))
print("\n".join(lines))
