"""Experiment 04b table.  Env: interp.   python experiments/04_specificity/analyze_reverse.py
Evil score per condition, plus the paired change vs the no-ablation baseline (same system prompt and question,
greedy) with a 95% bootstrap interval (10 000 resamples). Refusals (NaN evil) are dropped pairwise.
"""
import os

import numpy as np
import pandas as pd

A = "/data/coe9/artifacts/unpersona"
HERE = os.path.dirname(os.path.abspath(__file__))
R = f"{A}/exp04b_specificity_reverse"
C = {
    "evil prompt, no ablation (exp 02)": f"{A}/exp02_zero_ablation/evil_base_codex.csv",
    "evil prompt + mean abl. along e = v̂_20 (the standard evil direction) (exp 02)": f"{A}/exp02_zero_ablation/evil_mean_codex.csv",
    "A  evil prompt + mean abl. along e_perp (evil minus its sycophancy part)": f"{R}/evil_mean_eperp_codex.csv",
    "B  evil prompt + mean abl. along s = v̂_20 (the standard sycophancy direction)": f"{R}/evil_mean_s_codex.csv",
    "B  evil prompt + mean abl. along s_perp (sycophancy minus its evil part)": f"{R}/evil_mean_sperp_codex.csv",
    "no prompt, no ablation (exp 02)": f"{A}/exp02_zero_ablation/noprompt_base_codex.csv",
    "no prompt + mean abl. along e_perp": f"{R}/noprompt_mean_eperp_codex.csv",
    "no prompt + mean abl. along s": f"{R}/noprompt_mean_s_codex.csv",
    "no prompt + mean abl. along s_perp": f"{R}/noprompt_mean_sperp_codex.csv",
}
d = {k: pd.read_csv(v) for k, v in C.items()}
base = d["evil prompt, no ablation (exp 02)"].set_index(["sys_idx", "q_idx"]).evil
rng = np.random.default_rng(0)
rows = []
for k, df in d.items():
    r = dict(condition=k, n=len(df), evil=df.evil.mean(), frac_ge50=(df.evil >= 50).mean(),
             coherence=df.coherence.mean(), refusals=int(df.evil.isna().sum()))
    if "evil prompt +" in k:
        diff = (df.set_index(["sys_idx", "q_idx"]).evil - base).dropna().to_numpy()      # paired
        boots = rng.choice(diff, size=(10000, len(diff))).mean(1)
        r.update(diff_vs_base=diff.mean(), ci_lo=np.percentile(boots, 2.5), ci_hi=np.percentile(boots, 97.5))
    rows.append(r)
t = pd.DataFrame(rows)
txt = "# Experiment 04b results (generated by analyze_reverse.py)\n\n```\n" + t.round(2).to_string(index=False) + "\n```\n"
open(f"{HERE}/results_reverse.md", "w").write(txt)
print(txt)
