"""Experiment 04 table.  Env: interp.   python experiments/04_specificity/analyze.py
Sycophancy score per condition, plus the paired difference to the no-ablation baseline (same system prompt and
question, greedy) with a 95% bootstrap interval (10 000 resamples of the 100 prompt-question pairs).
"""
import os

import numpy as np
import pandas as pd

A = "/data/coe9/artifacts/unpersona"
HERE = os.path.dirname(os.path.abspath(__file__))
C = {  # label -> file
    "syc prompt, no ablation (exp 03)": f"{A}/exp03_mean_ablation_traits/sycophantic/trait_base_codex.csv",
    "syc prompt + mean abl. along s = v̂_20 (the standard sycophancy direction) (exp 03)": f"{A}/exp03_mean_ablation_traits/sycophantic/trait_mean_codex.csv",
    "syc prompt + mean abl. along e = v̂_20 (the standard evil direction)": f"{A}/exp04_specificity/syc_mean_e_codex.csv",
    "syc prompt + mean abl. along e_perp (evil minus its sycophancy part)": f"{A}/exp04_specificity/syc_mean_eperp_codex.csv",
    "no prompt, no ablation (exp 03)": f"{A}/exp03_mean_ablation_traits/sycophantic/noprompt_base_codex.csv",
    "no prompt + mean abl. along e": f"{A}/exp04_specificity/noprompt_mean_e_codex.csv",
    "no prompt + mean abl. along e_perp": f"{A}/exp04_specificity/noprompt_mean_eperp_codex.csv",
}
d = {k: pd.read_csv(v) for k, v in C.items()}
base = d["syc prompt, no ablation (exp 03)"].set_index(["sys_idx", "q_idx"]).sycophantic
rng = np.random.default_rng(0)
rows = []
for k, df in d.items():
    r = dict(condition=k, n=len(df), score=df.sycophantic.mean(), frac_ge50=(df.sycophantic >= 50).mean(),
             coherence=df.coherence.mean(), refusals=int(df.sycophantic.isna().sum()))
    if k.startswith("syc prompt +"):
        diff = (df.set_index(["sys_idx", "q_idx"]).sycophantic - base).dropna().to_numpy()    # [100] paired
        boots = rng.choice(diff, size=(10000, len(diff))).mean(1)
        r.update(diff_vs_base=diff.mean(), ci_lo=np.percentile(boots, 2.5), ci_hi=np.percentile(boots, 97.5))
    rows.append(r)
t = pd.DataFrame(rows)
txt = "# Experiment 04 results (generated by analyze.py)\n\n```\n" + t.round(2).to_string(index=False) + "\n```\n"
open(f"{HERE}/results.md", "w").write(txt)
print(txt)
