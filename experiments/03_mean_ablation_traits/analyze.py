"""Experiment 03 tables (sycophancy, hallucination; evil from experiment 02 for comparison).  Env: interp.
python experiments/03_mean_ablation_traits/analyze.py
Reads <cond>_codex.csv (trait score column named after the trait; NaN = judge said REFUSAL). Writes results.md.
"""
import os

import pandas as pd

BASE = "/data/coe9/artifacts/unpersona"
HERE = os.path.dirname(os.path.abspath(__file__))
SETS = {  # trait -> (folder, {label: file stem})
    "evil": (f"{BASE}/exp02_zero_ablation", {"noprompt_base": "noprompt_base", "noprompt_mean": "noprompt_mean",
                                              "trait_base": "evil_base", "trait_mean": "evil_mean"}),
    "sycophantic": (f"{BASE}/exp03_mean_ablation_traits/sycophantic", None),
    "hallucinating": (f"{BASE}/exp03_mean_ablation_traits/hallucinating", None),
}
LABELS = ["trait_base", "trait_mean", "noprompt_base", "noprompt_mean"]
DIRS = {"evil": "v̂_20 (the standard evil direction)", "sycophantic": "v̂_20 (the standard sycophancy direction)",
        "hallucinating": "v̂_16 (the standard hallucination direction)"}

lines = ["# Experiment 03 results (generated by analyze.py)\n",
         "Mean ablation along one fixed direction per trait, at every layer and token. Evil rows: experiment 02.\n"]
rows, per_sys = [], {}
for t, (folder, stems) in SETS.items():
    stems = stems or {l: l for l in LABELS}
    for lab in LABELS:
        f = f"{folder}/{stems[lab]}_codex.csv"
        if not os.path.exists(f):
            continue
        d = pd.read_csv(f)
        rows.append(dict(trait=t, direction=DIRS[t], condition=lab, n=len(d), score=d[t].mean(), score_std=d[t].std(),
                         frac_ge50=(d[t] >= 50).mean(), coherence=d.coherence.mean(), refusals=int(d[t].isna().sum()),
                         answer_tokens=d.n_answer_tokens.mean()))
        if lab.startswith("trait"):
            per_sys[(t, lab)] = d.groupby("sys_idx")[[t, "coherence"]].mean().set_axis(["score", "coherence"], axis=1)
lines += ["## Per trait and condition (score = that trait's 0-100 judge score)\n",
          "```\n" + pd.DataFrame(rows).round(2).to_string(index=False) + "\n```", ""]
s = pd.concat(per_sys, axis=1)
lines += ["## Trait system prompt (0-4): mean score, coherence over 20 questions\n", "```\n" + s.round(1).to_string() + "\n```", ""]
open(f"{HERE}/results.md", "w").write("\n".join(lines))
print("\n".join(lines))
